import { isPiiLikely, isSubstantive, type Answers } from './socratic-engine.js';
import type { ProjectReport } from './stack-analyzer.js';

const MAX_ITEMS = 6;

/** Splits a free-text answer into short items (lines, semicolons or commas). */
export function listItems(text: string | undefined): string[] {
  if (!isSubstantive(text)) return [];
  const source = text ?? '';
  const parts = source.includes('\n') ? source.split('\n') : source.split(/[;,]/);
  return parts
    .map((part) => part.replace(/^\s*(?:[-*]|\d+[.)])\s*/, '').trim())
    .filter((part) => part !== '')
    .slice(0, MAX_ITEMS);
}

/** Makes text safe inside a Mermaid `["…"]` label. */
export function mermaidLabel(text: string): string {
  const cleaned = text
    .replace(/[\r\n]+/g, ' ')
    .replace(/["[\]{}()<>|\\`#;&]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  const cut = cleaned.length > 40 ? `${cleaned.slice(0, 39).trimEnd()}…` : cleaned;
  return cut === '' ? 'unnamed' : cut;
}

function node(id: string, label: string): string {
  return `  ${id}["${mermaidLabel(label)}"]`;
}

function contextDiagram(name: string, answers: Answers): string {
  const users = listItems(answers.users);
  const systems = listItems(answers.integrations);
  const lines = ['flowchart LR', node('system', name)];
  (users.length > 0 ? users : ['Users']).forEach((user, index) => {
    lines.push(node(`u${String(index)}`, user), `  u${String(index)} --> system`);
  });
  systems.forEach((integration, index) => {
    lines.push(node(`x${String(index)}`, integration), `  system --> x${String(index)}`);
  });
  return lines.join('\n');
}

function containerDiagram(name: string, projects: readonly ProjectReport[]): string {
  const lines = ['flowchart TB', `  subgraph system["${mermaidLabel(name)}"]`];
  projects.forEach((project, index) => {
    const frameworks = project.frameworks.length > 0 ? ` ${project.frameworks.join(', ')}` : '';
    const label = `${project.path === '.' ? name : project.path}: ${project.language}${frameworks}`;
    lines.push(node(`c${String(index)}`, label));
  });
  if (projects.length === 0) lines.push(node('c0', 'Application'));
  lines.push('  end', node('store', 'Data store'));
  const count = Math.max(projects.length, 1);
  for (let index = 0; index < count; index += 1) lines.push(`  c${String(index)} --> store`);
  return lines.join('\n');
}

function section(title: string, body: string | undefined): string[] {
  return body === undefined || body.trim() === '' ? [] : [`## ${title}`, '', body.trim(), ''];
}

function bullets(text: string | undefined): string | undefined {
  const items = listItems(text);
  return items.length === 0 ? undefined : items.map((item) => `- ${item}`).join('\n');
}

export interface ReadmeInput {
  readonly name: string;
  readonly answers: Answers;
  /** The detected or planned projects; empty before a stack is chosen. */
  readonly projects: readonly ProjectReport[];
}

/** Renders a README from the domain answers, with Mermaid context and container diagrams. */
export function renderReadme(input: ReadmeInput): string {
  const { name, answers, projects } = input;
  const compliance = isPiiLikely(answers)
    ? [answers.regulations, answers.retention].filter((v) => v !== undefined).join('\n\n')
    : undefined;
  const parts = [
    `# ${name}`,
    '',
    ...section('Problem', answers.problem),
    ...section('Users', bullets(answers.users)),
    ...section('Core user journeys', bullets(answers.journeys)),
    ...section('Data', answers.data),
    ...section('Scale and service levels', [answers.scale, answers.availability, answers.recovery]
      .filter((v) => v !== undefined)
      .join('\n\n')),
    ...section(
      'Security',
      [
        answers.authentication && `**Authentication.** ${answers.authentication}`,
        answers.authorization && `**Authorisation.** ${answers.authorization}`,
        answers.boundaries && `**Boundaries.** ${answers.boundaries}`,
      ]
        .filter((v) => typeof v === 'string')
        .join('\n\n'),
    ),
    ...section('Integrations', bullets(answers.integrations)),
    ...section('Compliance', compliance),
    '## Architecture',
    '',
    '### System context',
    '',
    '```mermaid',
    contextDiagram(name, answers),
    '```',
    '',
    '### Containers',
    '',
    '```mermaid',
    containerDiagram(name, projects),
    '```',
    '',
    '---',
    '',
    '_Generated by `sentinel setup` from `.sentinel/domain.json`._',
    '',
  ];
  return parts.join('\n');
}
